use serde::{Deserialize, Serialize};
use std::fs;
use std::path::Path;

const APO_DIR: &str = r"C:\Program Files\EqualizerAPO\config";
const HRIR_DIR: &str = r"C:\Program Files\EqualizerAPO\config\HeSuVi\hrir";
const LOUDMAX: &str = r"C:\Program Files\Steinberg\VstPlugins\TDR Nova.dll";

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct Band {
    pub freq: f32,
    pub gain: f32,
    pub q: f32,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct ProfileConfig {
    pub bands: Vec<Band>,
    pub preamp: f32,
    pub virtualizer: bool,
    pub leveler: bool,
    pub enabled: bool,
}

#[derive(Debug, Serialize)]
pub struct EngineStatus {
    pub apo_installed: bool,
    pub config_path: String,
    pub hrir_count: usize,
    pub leveler_available: bool,
}

#[tauri::command]
pub fn engine_status() -> EngineStatus {
    let config = Path::new(APO_DIR).join("config.txt");
    let mut hrir_count = 0usize;
    if let Ok(entries) = fs::read_dir(HRIR_DIR) {
        hrir_count = entries
            .flatten()
            .filter(|e| {
                e.path()
                    .extension()
                    .map(|x| x.to_string_lossy().eq_ignore_ascii_case("wav"))
                    .unwrap_or(false)
            })
            .count();
    }
    EngineStatus {
        apo_installed: config.exists(),
        config_path: config.to_string_lossy().to_string(),
        hrir_count,
        leveler_available: Path::new(LOUDMAX).exists(),
    }
}

#[tauri::command]
pub fn list_hrirs() -> Vec<String> {
    let mut out = Vec::new();
    if let Ok(entries) = fs::read_dir(HRIR_DIR) {
        for e in entries.flatten() {
            let p = e.path();
            if p.extension()
                .map(|x| x.to_string_lossy().eq_ignore_ascii_case("wav"))
                .unwrap_or(false)
            {
                if let Some(name) = p.file_name().and_then(|n| n.to_str()) {
                    out.push(name.to_string());
                }
            }
        }
    }
    out.sort();
    out
}

#[tauri::command]
pub fn apply_profile(profile: ProfileConfig) -> Result<String, String> {
    let config_path = Path::new(APO_DIR).join("config.txt");

    if !Path::new(APO_DIR).exists() {
        return Err("Equalizer APO no encontrado en C:\\Program Files\\EqualizerAPO".into());
    }

    if config_path.exists() {
        let _ = fs::copy(&config_path, Path::new(APO_DIR).join("config.txt.auralis.bak"));
    }

    let mut s = String::from("# Generated by Auralis\n");

    if profile.enabled {
        s.push_str(&format!("Preamp: {:.1} dB\n", profile.preamp));

        for b in &profile.bands {
            if b.gain.abs() > 0.05 {
                s.push_str(&format!(
                    "Filter: ON PK Fc {:.0} Hz Gain {:.1} dB Q {:.2}\n",
                    b.freq, b.gain, b.q
                ));
            }
        }

        if profile.virtualizer {
            let hesuvi = Path::new(APO_DIR).join("HeSuVi").join("hesuvi.txt");
            if hesuvi.exists() {
                s.push_str(&format!("Include: {}\n", hesuvi.to_string_lossy()));
            }
        }

        // Volume leveler: usa la línea completa guardada (DLL + ChunkData)
        // para que Nova cargue con los parámetros configurados (threshold -18, gain +3...)
        if profile.leveler {
            let chunk_file = Path::new(APO_DIR).join("nova_vst.txt");
            if chunk_file.exists() {
                if let Ok(line) = fs::read_to_string(&chunk_file) {
                    let line = line.trim();
                    if !line.is_empty() {
                        s.push_str(line);
                        s.push('\n');
                    }
                }
            } else if Path::new(LOUDMAX).exists() {
                // Fallback sin chunk (Nova con preset default)
                s.push_str(&format!("VSTPlugin: Library \"{}\"\n", LOUDMAX));
            }
        }
    }

    fs::write(&config_path, s).map_err(|e| {
        format!(
            "No se pudo escribir la config: {}. ¿Ejecutaste la app como administrador?",
            e
        )
    })?;

    Ok(config_path.to_string_lossy().to_string())
}